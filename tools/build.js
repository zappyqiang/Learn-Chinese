/* Validates all lesson data and (re)generates:
     vendor/hanzi-writer.min.js      stroke animation library (MIT)
     vendor/hanzi/<codepoint>.json   stroke data for every character used (Arphic PL)
     data/chars.js                   per-character dictionary: readings, meaning, components
   Run:  cd tools && npm install && npm run build                                         */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
global.window = global; global.LC = {};
['lexicon', 'daily', 'classics'].forEach(f => require(path.join(root, 'data', f + '.js')));
require(path.join(root, 'js', 'core.js'));
require(path.join(root, 'js', 'evolution.js'));

let errors = 0;
const err = m => { errors++; console.error('ERROR: ' + m); };
const chars = new Set();
const isHan = c => /\p{Script=Han}/u.test(c);

// 1. lexicon sanity
for (const [w, e] of Object.entries(LC.lexicon)) {
  const n = [...w].length, syl = e.py.split(' ').length;
  if (n !== syl) err(`lexicon "${w}" has ${n} chars but ${syl} syllables (${e.py})`);
  [...w].forEach(c => chars.add(c));
}
// 2. every sentence resolves
let nSent = 0;
const check = (lesson, s) => {
  nSent++;
  for (const t of LC.parse(s[0])) {
    if (t.punct) continue;
    if (t.missing) { err(`[${lesson.id}] unknown word "${t.w}" in: ${s[0]}`); continue; }
    if ([...t.w].length !== t.py.split(' ').length) err(`[${lesson.id}] syllable mismatch "${t.w}" ${t.py}`);
    [...t.w].forEach(c => chars.add(c));
  }
  if (!s[1]) err(`[${lesson.id}] missing English: ${s[0]}`);
};
LC.daily.forEach(l => l.sentences.forEach(s => check(l, s)));
LC.classics.forEach(l => { l.sentences.forEach(s => check(l, s)); if (l.original) l.original.sentences.forEach(s => check(l, s)); [...l.zh].forEach(c => isHan(c) && chars.add(c)); });
if (LC.evolution) Object.keys(LC.evolution).forEach(c => chars.add(c));
console.log(`${Object.keys(LC.lexicon).length} words, ${nSent} sentences, ${chars.size} characters`);
if (errors) { console.error(errors + ' error(s)'); process.exit(1); }

// 3. vendor library + stroke data
const nm = path.join(__dirname, 'node_modules');
fs.copyFileSync(path.join(nm, 'hanzi-writer/dist/hanzi-writer.min.js'), path.join(root, 'vendor/hanzi-writer.min.js'));
fs.copyFileSync(path.join(nm, 'hanzi-writer-data/ARPHICPL.TXT'), path.join(root, 'vendor/hanzi/ARPHICPL.TXT'));
const outDir = path.join(root, 'vendor/hanzi');
fs.readdirSync(outDir).filter(f => f.endsWith('.json')).forEach(f => fs.unlinkSync(path.join(outDir, f)));
const noStroke = [];
for (const c of chars) {
  const src = path.join(nm, 'hanzi-writer-data', c + '.json');
  if (!fs.existsSync(src)) { noStroke.push(c); continue; }
  fs.copyFileSync(src, path.join(outDir, c.codePointAt(0).toString(16) + '.json'));
}
if (noStroke.length) console.warn('no stroke data for: ' + noStroke.join(''));

// 4. character dictionary
const hanzi = require('hanzi'); const log = console.log; console.log = () => {}; hanzi.start(); console.log = log;
const tone = s => {           // hao3 -> hǎo
  const marks = { a: 'āáǎàa', e: 'ēéěèe', i: 'īíǐìi', o: 'ōóǒòo', u: 'ūúǔùu', 'ü': 'ǖǘǚǜü' };
  return s.split(' ').map(sy => {
    const m = sy.toLowerCase().replace(/u:|v/g, 'ü').match(/^([a-zü]+)([1-5])$/); if (!m) return sy;
    let [, b, t] = m; t = +t - 1; if (t > 3) return b;
    const i = /a/.test(b) ? b.indexOf('a') : /e/.test(b) ? b.indexOf('e') : /ou/.test(b) ? b.indexOf('o') : b.search(/[iouü](?![iouü])/);
    return i < 0 ? b : b.slice(0, i) + marks[b[i]][t] + b.slice(i + 1);
  }).join(' ');
};
const out = {};
for (const c of [...chars].sort()) {
  const e = {};
  const defs = (hanzi.definitionLookup(c, 's') || []).filter(d => !/^(surname|variant of|old variant|used in|see )/i.test(d.definition) && /^[a-z]/.test(d.pinyin));
  e.r = defs.slice(0, 3).map(d => [tone(d.pinyin), d.definition.split('/').filter(x => !/^(CL:|surname |abbr\.|variant|Kangxi|old variant|see )/.test(x)).slice(0, 4).join('; ')]).filter(r => r[1]);
  try {
    const d = hanzi.decompose(c);
    const c1 = (d.components1 || []).filter(x => x !== 'No glyph available' && x !== c);
    if (c1.length > 1) e.c = c1.map(x => { const m = hanzi.getRadicalMeaning(x); return m && m !== 'N/A' ? [x, m] : [x]; });
  } catch (_) {}
  const f = hanzi.getCharacterFrequency(c); if (f && f.number) e.f = +f.number;
  e.s = fs.existsSync(path.join(nm, 'hanzi-writer-data', c + '.json')) ? JSON.parse(fs.readFileSync(path.join(nm, 'hanzi-writer-data', c + '.json'))).strokes.length : 0;
  out[c] = e;
}
fs.writeFileSync(path.join(root, 'data/chars.js'),
  '/* GENERATED by tools/build.js — do not edit. Readings & definitions: CC-CEDICT (CC BY-SA 4.0). Components: cjk-decomp. */\nwindow.LC = window.LC || {};\nLC.chars = ' + JSON.stringify(out) + ';\n');
console.log('wrote data/chars.js and ' + (chars.size - noStroke.length) + ' stroke files');
